"""Generate the embedded LCD artwork (include/console_art.h).

Fonts are pre-rendered anti-aliased Arial Bold, 4 bits per pixel.
Check the real screens on the device with: python scripts/screenshot.py <name> [keys]
"""

import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
SIZE = (280, 240)
CYAN = (0, 205, 228)
RULE = (30, 40, 48)
CHARS = "0123456789.+->gr /ABCDEFGHIJKLMNOPQRSTUVWXYZ#()',_:&"


def font(folder, size, italic=False):
    return ImageFont.truetype(str(folder / ("arialbi.ttf" if italic else "arialbd.ttf")), size)


def rgb565(rgb):
    r, g, b = rgb
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def mask_for(text, face):
    left, top, right, bottom = face.getbbox(text, anchor="ls")
    mask = Image.new("L", (max(right - left, 0), max(bottom - top, 0)))
    ImageDraw.Draw(mask).text((-left, -top), text, font=face, anchor="ls", fill=255)
    return mask.point(lambda p: 17 * (p >> 4)), left, top, round(face.getlength(text))


def static_art(folder):
    """Header shared by every screen: wordmark and separator."""
    image = Image.new("RGB", SIZE)
    draw = ImageDraw.Draw(image)
    draw.text((14, 30), "PowderReload", font=font(folder, 13, True), fill=CYAN, anchor="ls")
    draw.line((14, 40, 266, 40), fill=RULE)
    return image


def emit(image, glyphs):
    header = [
        "// Generated by scripts/generate_console_art.py.",
        "#pragma once", "#include <stdint.h>", "namespace ConsoleArt {",
        "struct Span { uint16_t x, y, length, color; };",
        "struct Glyph { char character; int8_t left, top; uint8_t width, height, advance; uint32_t offset; };",
        "constexpr Span Background[] = {",
    ]
    for y in range(SIZE[1]):
        row = [rgb565(image.getpixel((x, y))) for x in range(SIZE[0])]
        start = 0
        while start < len(row):
            end = start + 1
            while end < len(row) and row[end] == row[start]:
                end += 1
            if row[start]:
                header.append(f"    {{{start}, {y}, {end-start}, 0x{row[start]:04x}}},")
            start = end
    header.append("};")
    for name, glyph_set in glyphs.items():
        pixels = []
        header.append(f"constexpr Glyph {name}[] = {{")
        for char, (mask, left, top, advance) in glyph_set.items():
            literal = "\\" + char if char in "'\\" else char
            header.append(f"    {{'{literal}', {left}, {top}, {mask.width}, {mask.height}, {advance}, {len(pixels)}}},")
            levels = [value >> 4 for value in mask.tobytes()]
            if len(levels) % 2:
                levels.append(0)
            pixels.extend((levels[i] << 4) | levels[i + 1] for i in range(0, len(levels), 2))
        header.append("};")
        header.append(f"constexpr uint8_t {name}Pixels[] = {{")
        for i in range(0, len(pixels), 24):
            header.append("    " + ", ".join(f"0x{p:02x}" for p in pixels[i:i + 24]) + ",")
        if not pixels:
            header.append("    0,")
        header.append("};")
    header.append("}")
    (ROOT / "include" / "console_art.h").write_text("\n".join(header) + "\n", encoding="utf-8")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--fonts", type=Path, default=Path("C:/Windows/Fonts"))
    args = parser.parse_args()
    digits = "0123456789.+-"
    glyphs = {
        "Large": {c: mask_for(c, font(args.fonts, 80)) for c in digits},
        "Unit": {c: mask_for(c, font(args.fonts, 49)) for c in "gr"},
        "Mid": {c: mask_for(c, font(args.fonts, 28)) for c in digits},
        "Small": {c: mask_for(c, font(args.fonts, 15)) for c in CHARS},
        "Menu": {c: mask_for(c, font(args.fonts, 20)) for c in CHARS},
        "Hint": {c: mask_for(c, font(args.fonts, 11)) for c in CHARS},
    }
    emit(static_art(args.fonts), glyphs)


if __name__ == "__main__":
    main()
